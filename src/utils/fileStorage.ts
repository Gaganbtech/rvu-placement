/**
 * Triggers a real browser file download for a given file name and data URL / URL
 */
export function triggerFileDownload(fileName: string, dataUrl?: string, fallbackContent?: string): void {
  const downloadUrl = dataUrl || (fallbackContent 
    ? `data:text/plain;charset=utf-8,${encodeURIComponent(fallbackContent)}`
    : `data:text/plain;charset=utf-8,${encodeURIComponent(`Document: ${fileName}\nSource: RVU Placement Portal`)}`);

  const anchor = document.createElement('a');
  anchor.href = downloadUrl;
  anchor.download = fileName;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
}
